"""Runs the five seeded scenarios against the baseline rule file and writes the results report
(required deliverable): reports/scenario_results.md and reports/scenario_results.json.

Also records the AC4 comparison: the same inputs under config v1.0.0 and the v1.1.0 sample.
Exit code is non-zero if any scenario misses its predefined expected outcome.

Usage:  python scripts/run_scenarios.py
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "backend"))

from app.config import load_ruleset  # noqa: E402
from app.engine import evaluate  # noqa: E402
from app.explain import show  # noqa: E402
from app.ingest import build_case  # noqa: E402
from app.models import FindingResult  # noqa: E402
from app.scenarios import load_scenarios  # noqa: E402

BASELINE = REPO / "config" / "rules" / "ach_db_next_day.yaml"
SAMPLE = REPO / "config" / "rules" / "samples" / "ach_db_next_day.v1.1.0.yaml"
OUT = REPO / "reports"


def main() -> int:
    cfg = load_ruleset(BASELINE)
    sample = load_ruleset(SAMPLE)
    rows, ac4 = [], []
    for s in load_scenarios(REPO / "data" / "scenarios"):
        case = build_case(s.request, s.change)
        result = evaluate(case, cfg, scenario_id=s.id)
        actual = sorted((f.rule_id, f.field, f.exception_type.value) for f in result.findings
                        if f.result is FindingResult.EXCEPTION)
        expected = sorted((e["rule_id"], e["field"], e["exception_type"]) for e in s.expected["exceptions"])
        passed = result.overall.value == s.expected["overall"] and actual == expected
        rows.append({
            "scenario_id": s.id, "name": s.name, "seeded_condition": s.seeded_condition,
            "organizer_expected_outcome": s.organizer_expected_outcome,
            "expected_overall": s.expected["overall"], "actual_overall": result.overall.value,
            "expected_exceptions": [list(e) for e in expected], "actual_exceptions": [list(a) for a in actual],
            "status": "PASS" if passed else "FAIL",
            "request_id": result.request_id, "change_id": result.change_id,
            "input_digest": result.input_digest, "findings_digest": result.findings_digest,
            "exception_details": [
                {"field": f.field_label, "expected": show(f.expected_value), "actual": show(f.actual_value),
                 "rule": f"{f.rule_id} v{f.rule_version}", "reason": f.reason}
                for f in result.findings if f.result is FindingResult.EXCEPTION
            ],
        })
        alt = evaluate(case, sample, scenario_id=s.id)
        ac4.append({"scenario_id": s.id, "v1_0_0": result.overall.value, "v1_1_0": alt.overall.value,
                    "changed": result.overall != alt.overall,
                    "new_rules": sorted({f.rule_id for f in alt.findings if f.result is FindingResult.EXCEPTION}
                                        - {f.rule_id for f in result.findings if f.result is FindingResult.EXCEPTION})})

    passed = sum(r["status"] == "PASS" for r in rows)
    generated = datetime.now(timezone.utc).isoformat(timespec="seconds")
    OUT.mkdir(exist_ok=True)
    (OUT / "scenario_results.json").write_text(json.dumps({
        "generated_at": generated, "label": "SYNTHETIC DATA · SIMULATED SYSTEMS · PROTOTYPE",
        "config": {"file": BASELINE.name, "version": cfg.ruleset.ruleset.version, "sha256": cfg.sha256},
        "summary": {"total": len(rows), "passed": passed}, "scenarios": rows, "ac4_comparison": ac4,
    }, indent=2) + "\n")

    md = [
        "# Seeded scenario test results",
        "",
        "> SYNTHETIC DATA · SIMULATED SYSTEMS · PROTOTYPE. Generated by `scripts/run_scenarios.py`.",
        "",
        f"- **Generated:** {generated}",
        f"- **Rule configuration:** `{BASELINE.relative_to(REPO)}` v{cfg.ruleset.ruleset.version} · sha256 `{cfg.sha256}`",
        f"- **Result:** **{passed} / {len(rows)} scenarios produced their predefined expected outcome**",
        "",
        "| # | Scenario | Organizer expected outcome | Expected | Actual | Exceptions raised (rule · field · type) | Result |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        exc = "<br>".join(" · ".join(a) for a in r["actual_exceptions"]) or "none"
        md.append(f"| {r['scenario_id']} | {r['name']} | {r['organizer_expected_outcome']} | {r['expected_overall']} "
                  f"| {r['actual_overall']} | {exc} | {'✅ PASS' if r['status'] == 'PASS' else '❌ FAIL'} |")
    md += ["", "## Exception detail (AC3)", ""]
    for r in rows:
        for d in r["exception_details"]:
            md.append(f"- **{r['scenario_id']} · {d['field']}** — expected `{d['expected']}`, actual `{d['actual']}`, "
                      f"rule {d['rule']}. {d['reason']}")
    md += ["", "## Configuration-driven rule change (AC4)", "",
           f"Same inputs, rule file v1.0.0 vs `{SAMPLE.relative_to(REPO)}` (EVD-002 `enabled: false` → `true`). No code change.",
           "", "| Scenario | v1.0.0 | v1.1.0 | Changed | New exception rules |", "|---|---|---|---|---|"]
    for a in ac4:
        md.append(f"| {a['scenario_id']} | {a['v1_0_0']} | {a['v1_1_0']} | {'yes' if a['changed'] else 'no'} "
                  f"| {', '.join(a['new_rules']) or '—'} |")
    md.append("")
    (OUT / "scenario_results.md").write_text("\n".join(md))
    print(f"{passed}/{len(rows)} seeded scenarios match expected outcomes -> reports/scenario_results.md")
    return 0 if passed == len(rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
